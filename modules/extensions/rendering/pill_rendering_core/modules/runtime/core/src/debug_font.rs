//! The bitmap font debug labels are drawn in: one 5 by 7 pixel glyph per
//! character, shared by every renderer.
//!
//! # Responsibilities
//!
//! - Hold the glyphs as readable pixel art ([\GLYPHS\]) and the size of a glyph
//!   cell ([\GLYPH_WIDTH\], [\GLYPH_HEIGHT\]).
//! - Turn a character into its glyph's pixel rows ([\glyph_rows\]), uppercase
//!   and with no glyph for anything the font does not have.
//!
//! # Design
//!
//! Debug labels need to be readable, not pretty, and they must not depend on a
//! font file being found at runtime, so the glyphs live in the source. One table
//! serves both renderers: the GPU one builds a texture atlas from it and the
//! panel one draws the rows straight into its framebuffer, so a label reads the
//! same on either.
//!
//! A lowercase letter draws as its uppercase form.

// =============================================================================
// Constants
// =============================================================================

/// Glyph width in pixels.
pub const GLYPH_WIDTH: u32 = 5;

/// Glyph height in pixels.
pub const GLYPH_HEIGHT: u32 = 7;

/// How many pixel rows one glyph has.
pub const GLYPH_ROWS: usize = GLYPH_HEIGHT as usize;

/// The character drawn for one the font does not have.
pub const MISSING_GLYPH: char = '?';

