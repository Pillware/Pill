/// The pixel rows of \character\'s glyph, the top row first, or \None\ when the
/// font has no glyph for it.
///
/// A lowercase letter uses its uppercase glyph, and one row's five pixels sit
/// in its low bits with the leftmost in bit 4.
pub fn glyph_rows(character: char) -> Option<[u8; GLYPH_ROWS]> {
    let uppercase = character.to_ascii_uppercase();
    let (_, art) = GLYPHS
        .iter()
        .find(|(candidate, _)| *candidate == uppercase)?;
    let mut rows = [0_u8; GLYPH_ROWS];
    for (row, pixels) in art.split('/').enumerate() {
        for (column, pixel) in pixels.chars().enumerate() {
            if pixel == '#' {
                rows[row] |= 1 << (GLYPH_WIDTH as usize - 1 - column);
            }
        }
    }
    Some(rows)
}
